# ---------------------------------------------------------------------------
# TestConnectorToolNames - prove invalid bodies are denied before write
#
# These tests simulate the actual Codex GitHub connector tool names
# (``mcp__codex_apps__github._create_pull_request``) through the existing
# ``preflight_pr_template_shape`` and ``preflight_pr_body_required_sections``
# hooks to satisfy issue #938 acceptance criterion 1 and verification item 1.
