_CODEX_CREATE_PR = "mcp__codex_apps__github._create_pull_request"
_CODEX_UPDATE_PR = "mcp__codex_apps__github._update_pull_request"


class TestConnectorToolInvalidBodyDenied:
    """Prove invalid bodies are denied before the GitHub API write."""

    @pytest.mark.parametrize(
        "tool_name",
        [_CODEX_CREATE_PR, _CODEX_UPDATE_PR],
    )
    def test_missing_required_sections_denies(self, tool_name: str) -> None:
        out = prs.decide(tool_name, {"body": "## Verification\n\nsome text\n"})
        assert out is not None
        assert out["hookSpecificOutput"]["permissionDecision"] == "deny"

    @pytest.mark.parametrize(
        "tool_name",
        [_CODEX_CREATE_PR, _CODEX_UPDATE_PR],
    )
    def test_missing_verification_pairs_denies(self, tool_name: str) -> None:
        # Has required sections but no Verification command/result pairs.
        body = (
            _SECTIONS_OK
            + "## Verification\n\nno command pairs here\n\n"
            + _CHECKLIST_OK
            + "\n"
            + _FOOTER_OK
        )
        out = pts.decide(tool_name, {"body": body})
        assert out is not None
        assert out["hookSpecificOutput"]["permissionDecision"] == "deny"

    @pytest.mark.parametrize(
        "tool_name",
        [_CODEX_CREATE_PR, _CODEX_UPDATE_PR],
    )
    def test_missing_checklist_subsections_denies(self, tool_name: str) -> None:
        body = (
            _SECTIONS_OK
            + _VERIFICATION_OK
            + "\n## Checklist\n\n### Bootstrap\n\n- [ ] x\n\n"
            + _FOOTER_OK
        )
        out = pts.decide(tool_name, {"body": body})
        assert out is not None
        assert out["hookSpecificOutput"]["permissionDecision"] == "deny"

    @pytest.mark.parametrize(
        "tool_name",
        [_CODEX_CREATE_PR, _CODEX_UPDATE_PR],
    )
    def test_missing_footer_denies(self, tool_name: str) -> None:
        body = _SECTIONS_OK + _VERIFICATION_OK + "\n" + _CHECKLIST_OK
        out = pts.decide(tool_name, {"body": body})
        assert out is not None
        assert out["hookSpecificOutput"]["permissionDecision"] == "deny"


