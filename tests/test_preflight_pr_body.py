"""Tests for ``scripts/preflight_pr_body.py``.

Verifies that the single-command local PR body validator:
* reports every missing required section
* catches Verification command/result pair violations
* catches missing Checklist H3 subsections
* catches missing attribution footer
* catches non-ASCII content
* optionally validates the issue reference when ``--issue`` is given
* passes when the body is fully conformant

Includes test fixtures that use the Codex GitHub connector tool name
(``mcp__codex_apps__github._create_pull_request``) to satisfy the
issue #938 acceptance criterion that tests simulate the actual connector
tool names and prove valid bodies are allowed and invalid bodies are denied
before write.

Refs #938.
"""

from __future__ import annotations

from pathlib import Path

import preflight_pr_body as prb
import preflight_pr_body_required_sections as prs
import preflight_pr_template_shape as pts
import pytest

pytestmark = pytest.mark.shard_preflight


@pytest.fixture(autouse=True)
def _clear_remote_env(monkeypatch: pytest.MonkeyPatch) -> None:
    """Isolate from the ambient CLAUDE_CODE_REMOTE signal (#1025).

    ``main()`` resolves the harness footer relaxation from this var;
    clearing it keeps the default-path tests deterministic regardless of
    where the suite runs (the remote Claude web harness sets it to
    ``true``). Harness-path tests set it explicitly.
    """
    monkeypatch.delenv("CLAUDE_CODE_REMOTE", raising=False)


