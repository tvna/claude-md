_VERIFICATION_OK = """## Verification

- command: `pytest -q`
  result: `exit 0 (684 passed)`
"""

_CHECKLIST_OK = """## Checklist

### Bootstrap

- [ ] facts split honest

### After-merge (CI)

- [ ] CI green

### Post-merge (auto-retro signal)

- [ ] linked issue closed
"""

_FOOTER_OK = "_Generated by [Codex](https://openai.com/codex)_\n"

_GOOD_BODY = _VERIFICATION_OK + "\n" + _CHECKLIST_OK + "\n" + _FOOTER_OK


