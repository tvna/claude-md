class TestEvaluate:
    def test_good_body_returns_empty(self) -> None:
        assert shape.evaluate(_GOOD_BODY) == []

    def test_missing_verification_returns_error(self) -> None:
        body = _CHECKLIST_OK
        errors = shape.evaluate(body)
        assert errors
        assert any("Verification" in e for e in errors)

    def test_missing_checklist_subsection_returns_error(self) -> None:
        body = (
            _VERIFICATION_OK
            + "\n## Checklist\n\n### Bootstrap\n\n- [ ] x\n\n"
            + _FOOTER_OK
        )
        errors = shape.evaluate(body)
        assert any("After-merge" in e for e in errors)
        assert any("Post-merge" in e for e in errors)

    def test_missing_agent_footer_returns_error(self) -> None:
        body = _VERIFICATION_OK + "\n" + _CHECKLIST_OK
        errors = shape.evaluate(body)
        assert any("agent-attribution footer" in e for e in errors)

    def test_duplicate_agent_footer_returns_error(self) -> None:
        # Manual footer + harness auto-appended session footer (#784).
        body = (
            _VERIFICATION_OK
            + "\n"
            + _CHECKLIST_OK
            + "\n"
            + _FOOTER_OK
            + "\n"
            + _FOOTER_OK
        )
        errors = shape.evaluate(body)
        assert any("multiple agent-attribution footers" in e for e in errors)


