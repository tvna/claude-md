"""Tests for ``scripts/preflight_pr_template_shape.py``.

Mirrors the structure of ``tests/test_pr_body_close_keyword_gate.py``:
pure decision function tested in isolation, then the stdin/stdout
boundary of :func:`main` with monkeypatched ``sys.stdin``.

The ``scripts/`` directory is on ``sys.path`` via ``pythonpath`` under
``[tool.pytest.ini_options]`` in ``pyproject.toml``.
"""

from __future__ import annotations

import io
import json
from typing import Any

import preflight_pr_template_shape as shape
import pytest

pytestmark = pytest.mark.shard_preflight


@pytest.fixture(autouse=True)
def _clear_remote_env(monkeypatch: pytest.MonkeyPatch) -> None:
    """Isolate from the ambient CLAUDE_CODE_REMOTE signal (#1025).

    The footer relaxation keys off this var; clearing it keeps the
    non-harness tests deterministic regardless of where the suite runs
    (the remote Claude web harness sets it to ``true``). Tests that
    exercise the harness path set it explicitly.
    """
    monkeypatch.delenv("CLAUDE_CODE_REMOTE", raising=False)


